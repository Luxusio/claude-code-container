        "  if ($Profile -eq 'windows-server') {",
        "    Set-CccAcquireStage 'hyper-v-base-image-download-failed'",
        "    $ValidateMicrosoftHop = { param([Uri]$CandidateUri) $HostName = $CandidateUri.DnsSafeHost.ToLowerInvariant(); return ($CandidateUri.Scheme -eq 'https' -and ($HostName -eq 'go.microsoft.com' -or $HostName -eq 'aka.ms' -or $HostName -eq 'download.microsoft.com' -or $HostName.EndsWith('.download.microsoft.com') -or $HostName -eq 'software-static.download.prss.microsoft.com')) }",
        "    $ValidateMicrosoftVhdx = { param([Uri]$FinalUri) $HostName = $FinalUri.DnsSafeHost.ToLowerInvariant(); return ($FinalUri.Scheme -eq 'https' -and $FinalUri.AbsolutePath.EndsWith('.vhdx', [StringComparison]::OrdinalIgnoreCase) -and ($HostName -eq 'download.microsoft.com' -or $HostName.EndsWith('.download.microsoft.com') -or $HostName -eq 'software-static.download.prss.microsoft.com')) }",
        "    Save-BoundedDownload $WindowsUrl $PartialPath $WindowsMaxBytes $ValidateMicrosoftHop $ValidateMicrosoftVhdx",
        "  } else {",
        "    New-Item -ItemType Directory -Path $WorkPath -Force | Out-Null",
        "    $ArchiveDownloadPath = Join-Path $WorkPath 'source.download.zip'",
        "    $ArchivePath = $SourceArchivePath",
        "    $ExtractPath = Join-Path $WorkPath 'extract'",
        "    $ValidateCanonical = { param([Uri]$FinalUri) return ($FinalUri.Scheme -eq 'https' -and $FinalUri.DnsSafeHost.ToLowerInvariant() -eq 'partner-images.canonical.com') }",
        "    $ArchiveReady = $false",
        "    if (Test-Path -LiteralPath $ArchivePath -PathType Container) { throw 'hyper-v-base-image-hash-failed' }",
        "    if (Test-Path -LiteralPath $ArchivePath -PathType Leaf) {",
        "      Set-CccAcquireStage 'hyper-v-base-image-hash-failed'",
        "      $CachedArchive = Get-Item -LiteralPath $ArchivePath -Force -ErrorAction Stop",
        "      if (-not $CachedArchive.PSIsContainer -and ($CachedArchive.Attributes -band [IO.FileAttributes]::ReparsePoint) -eq 0 -and [long]$CachedArchive.Length -gt 0 -and [long]$CachedArchive.Length -le $UbuntuMaxBytes) {",
        "        $ArchiveHandle = [IO.File]::Open($ArchivePath, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::Read)",
        "        $CachedHash = (Get-FileHash -LiteralPath $ArchivePath -Algorithm SHA256 -ErrorAction Stop).Hash.ToLowerInvariant()",
        "        $ArchiveReady = $CachedHash -eq $UbuntuArchiveSha256",
        "        if (-not $ArchiveReady) { $ArchiveHandle.Dispose(); $ArchiveHandle = $null }",
        "      }",
        "      if (-not $ArchiveReady) { Remove-Item -LiteralPath $ArchivePath -Force -ErrorAction Stop }",
        "    }",
        "    if (-not $ArchiveReady) {",
        "      Set-CccAcquireStage 'hyper-v-base-image-download-failed'",
        "      Save-BoundedDownload $UbuntuArchiveUrl $ArchiveDownloadPath $UbuntuMaxBytes $ValidateCanonical $ValidateCanonical",
        "      Set-CccAcquireStage 'hyper-v-base-image-hash-failed'",
        "      $ActualHash = (Get-FileHash -LiteralPath $ArchiveDownloadPath -Algorithm SHA256 -ErrorAction Stop).Hash.ToLowerInvariant()",
        "      if ($ActualHash -ne $UbuntuArchiveSha256) { throw 'hyper-v-base-image-checksum-mismatch' }",
        "      Assert-NoReparsePath $ArchiveDownloadPath",
        "      Assert-NoReparsePath $ArchivePath",
        "      Move-Item -LiteralPath $ArchiveDownloadPath -Destination $ArchivePath -ErrorAction Stop",
        "      $ArchiveHandle = [IO.File]::Open($ArchivePath, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::Read)",
        "      $LockedHash = (Get-FileHash -LiteralPath $ArchivePath -Algorithm SHA256 -ErrorAction Stop).Hash.ToLowerInvariant()",
        "      if ($LockedHash -ne $UbuntuArchiveSha256) { $DiscardArchive = $true; throw 'hyper-v-base-image-checksum-mismatch' }",
        "    }",
        "    Set-CccAcquireStage 'hyper-v-base-image-archive-check-failed'",
        "    $ArchiveEntries = @(& tar.exe -tf $ArchivePath)",
        "    $MaximumArchiveEntries = 64",
        "    $MaximumRegularFiles = 8",
        "    $MaximumExtractedBytes = [long]64GB",
