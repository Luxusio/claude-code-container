import { resolve } from "path";

import {
    type HyperVProviderCommand,
    type HyperVBaseImageOptions,
    type HyperVAcquireBaseImageOptions,
} from "./contracts.js";
import {
    HYPER_V_RESULT_MARKER,
    psQuote,
    assertPlainPath,
    assertPathInside,
    jsonScript,
    command,
} from "./core.js";
import { HYPER_V_UBUNTU_IMAGE_SHA256, HYPER_V_UBUNTU_IMAGE_URL, HYPER_V_UBUNTU_VIRTUAL_SIZE_BYTES } from "./ubuntu-image.js";
import { hyperVUbuntuAzureImageAcquisitionLines } from "./ubuntu-image-acquisition.js";

export function hyperVPrepareBaseImageCommand(options: HyperVBaseImageOptions): HyperVProviderCommand {
    const sourceImagePath = assertPathInside(options.sourceRoot, options.sourceImagePath, "base-image-source");
    const imagePath = assertPathInside(options.imageRoot, options.imagePath, "base-image-target");
    if (!/\.vhdx$/i.test(sourceImagePath) || !/\.vhdx$/i.test(imagePath)) throw new Error("hyper-v-base-image-format-unsupported");
    const tempPath = `${imagePath}.partial`;
    const script = jsonScript([
        `$Profile = ${psQuote(options.profile)}`,
        `$SourceImage = ${psQuote(sourceImagePath)}`,
        `$ImagePath = ${psQuote(imagePath)}`,
        `$TempPath = ${psQuote(tempPath)}`,
        "Assert-NoReparsePath $SourceImage",
        "Assert-NoReparsePath $ImagePath",
        "Assert-NoReparsePath $TempPath",
        "function Get-CccVhdGeneration([string]$Path) {",
        "  $Mounted = $null",
        "  $Generation = $null",
        "  $InspectionError = $null",
        "  $DismountError = $null",
        "  try {",
        "    $Mounted = Mount-VHD -Path $Path -ReadOnly -NoDriveLetter -Passthru -ErrorAction Stop",
        "    $Disk = $Mounted | Get-Disk -ErrorAction Stop",
        "    $Generation = switch ([string]$Disk.PartitionStyle) { 'GPT' { 2 } 'MBR' { 1 } default { throw 'hyper-v-base-image-partition-style-unsupported' } }",
        "  } catch { $InspectionError = $_ } finally {",
        "    if ($Mounted) { try { Dismount-VHD -Path $Path -ErrorAction Stop } catch { $DismountError = $_ } }",
        "  }",
        "  if ($DismountError) { throw 'hyper-v-base-image-dismount-failed' }",
        "  if ($InspectionError) { throw $InspectionError }",
        "  return $Generation",
        "}",
        "if (-not (Test-Path -LiteralPath $SourceImage -PathType Leaf)) { throw 'hyper-v-base-image-source-not-found' }",
        "$SourceHash = (Get-FileHash -LiteralPath $SourceImage -Algorithm SHA256 -ErrorAction Stop).Hash.ToLowerInvariant()",
        "if (Test-Path -LiteralPath $ImagePath -PathType Leaf) {",
        "  $ExistingHash = (Get-FileHash -LiteralPath $ImagePath -Algorithm SHA256 -ErrorAction Stop).Hash.ToLowerInvariant()",
        "  if ($ExistingHash -ne $SourceHash) { throw 'hyper-v-base-image-profile-conflict' }",
        "  $ExistingVhd = Get-VHD -Path $ImagePath -ErrorAction Stop",
        "  if ([string]$ExistingVhd.VhdFormat -ne 'VHDX' -or [string]$ExistingVhd.VhdType -eq 'Differencing' -or $ExistingVhd.ParentPath) { throw 'hyper-v-base-image-invalid-parent' }",
        "  $Generation = Get-CccVhdGeneration $ImagePath",
        "  $Result = [ordered]@{ ok = $true; profile = $Profile; imagePath = $ImagePath; sha256 = $ExistingHash; sizeBytes = [long](Get-Item -LiteralPath $ImagePath).Length; virtualSizeBytes = [long]$ExistingVhd.Size; vhdType = [string]$ExistingVhd.VhdType; generation = $Generation; reused = $true }",
        "  $Result | ConvertTo-Json -Compress -Depth 5",
        "  exit 0",
        "}",
        "New-Item -ItemType Directory -Path (Split-Path -Parent $ImagePath) -Force | Out-Null",
        "Assert-NoReparsePath $TempPath",
        "Remove-Item -LiteralPath $TempPath -Force -ErrorAction SilentlyContinue",
        "try {",
        "  Copy-Item -LiteralPath $SourceImage -Destination $TempPath -ErrorAction Stop",
        "  $Vhd = Get-VHD -Path $TempPath -ErrorAction Stop",
        "  if ([string]$Vhd.VhdFormat -ne 'VHDX' -or [string]$Vhd.VhdType -eq 'Differencing' -or $Vhd.ParentPath) { throw 'hyper-v-base-image-invalid-parent' }",
        "  $CopiedHash = (Get-FileHash -LiteralPath $TempPath -Algorithm SHA256 -ErrorAction Stop).Hash.ToLowerInvariant()",
        "  if ($CopiedHash -ne $SourceHash) { throw 'hyper-v-base-image-copy-hash-mismatch' }",
        "  Assert-NoReparsePath $TempPath",
        "  Assert-NoReparsePath $ImagePath",
        "  Move-Item -LiteralPath $TempPath -Destination $ImagePath -ErrorAction Stop",
        "  $Generation = Get-CccVhdGeneration $ImagePath",
        "  $Result = [ordered]@{ ok = $true; profile = $Profile; imagePath = $ImagePath; sha256 = $CopiedHash; sizeBytes = [long](Get-Item -LiteralPath $ImagePath).Length; virtualSizeBytes = [long]$Vhd.Size; vhdType = [string]$Vhd.VhdType; generation = $Generation; reused = $false }",
        "  $Result | ConvertTo-Json -Compress -Depth 5",
        "} finally {",
        "  Assert-NoReparsePath $TempPath",
        "  Remove-Item -LiteralPath $TempPath -Force -ErrorAction SilentlyContinue",
        "}",
    ]);
    return command(options.executable, script);
}

export function hyperVAcquireBaseImageCommand(options: HyperVAcquireBaseImageOptions): HyperVProviderCommand {
    const imageRoot = assertPlainPath(options.imageRoot, "base-image-root");
    if (options.expectedGeneration !== 1 && options.expectedGeneration !== 2) {
        throw new Error("hyper-v-base-image-generation-invalid");
    }
    if (options.profile !== "windows-server" && options.profile !== "ubuntu-lts") {
        throw new Error("hyper-v-base-image-profile-not-automatic");
    }
    const profileGeneration = 2;
    if (options.expectedGeneration !== profileGeneration) {
        throw new Error("hyper-v-base-image-generation-mismatch");
    }
    const profileRoot = resolve(imageRoot, options.profile);
    const imagePath = resolve(profileRoot, "base.vhdx");
    const partialPath = resolve(profileRoot, "base.partial.vhdx");
    const workPath = resolve(profileRoot, ".acquire-work");
    const sourceArchivePath = resolve(profileRoot, "source.vhd.tar.gz");
    const script = jsonScript([
        `$Profile = ${psQuote(options.profile)}`,
        `$ImageRoot = ${psQuote(imageRoot)}`,
        `$ProfileRoot = ${psQuote(profileRoot)}`,
        `$ImagePath = ${psQuote(imagePath)}`,
        `$PartialPath = ${psQuote(partialPath)}`,
        `$WorkPath = ${psQuote(workPath)}`,
        `$SourceArchivePath = ${psQuote(sourceArchivePath)}`,
        `$ExpectedGeneration = ${options.expectedGeneration}`,
        "$WindowsUrl = 'https://go.microsoft.com/fwlink/?clcid=0x409&country=us&culture=en-us&linkid=2345826'",
        `$UbuntuImageUrl = ${psQuote(HYPER_V_UBUNTU_IMAGE_URL)}`,
        `$UbuntuImageSha256 = ${psQuote(HYPER_V_UBUNTU_IMAGE_SHA256)}`,
        `$UbuntuVirtualSizeBytes = [long]${HYPER_V_UBUNTU_VIRTUAL_SIZE_BYTES}`,
        "$WindowsMaxBytes = [long]16GB",
        "$UbuntuMaxBytes = [long]5GB",
        "$script:CccAcquireStage = 'hyper-v-base-image-download-failed'",
        "$env:CCC_HYPER_V_STAGE = $script:CccAcquireStage",
        "function Set-CccAcquireStage([string]$Stage) {",
        "  if ($Stage -notmatch '^hyper-v-base-image-(download|hash|archive-check|extract|normalize|source-open|source-hash|source-inspection|copy|destination-create|convert|partial-open|partial-hash|partial-inspection|final-move|final-inspection|final-observation|work-cleanup)-failed$') { throw 'hyper-v-diagnostic-stage-invalid' }",
        "  $script:CccAcquireStage = $Stage",
        "  $env:CCC_HYPER_V_STAGE = $Stage",
        "  [Console]::Out.WriteLine(('CCC_HYPER_V_STAGE:' + $Stage))",
        "}",
        "function Protect-CccImageDirectory([string]$Path) {",
        "  try {",
        "    $CurrentSid = [Security.Principal.WindowsIdentity]::GetCurrent().User",
        "    $SystemSid = [Security.Principal.SecurityIdentifier]::new('S-1-5-18')",
        "    $AdministratorsSid = [Security.Principal.SecurityIdentifier]::new('S-1-5-32-544')",
        "    $AllowedSids = @($CurrentSid.Value, $SystemSid.Value, $AdministratorsSid.Value)",
        "    $DirectoryInheritance = [Security.AccessControl.InheritanceFlags]::ContainerInherit -bor [Security.AccessControl.InheritanceFlags]::ObjectInherit",
        "    $NoInheritance = [Security.AccessControl.InheritanceFlags]::None",
        "    $NoPropagation = [Security.AccessControl.PropagationFlags]::None",
        "    $FullControl = [Security.AccessControl.FileSystemRights]::FullControl",
        "    function Set-CccExactAcl([string]$Target, [bool]$Directory) {",
        "      $Security = if ($Directory) { [Security.AccessControl.DirectorySecurity]::new() } else { [Security.AccessControl.FileSecurity]::new() }",
        "      $Security.SetOwner($CurrentSid)",
        "      $Security.SetAccessRuleProtection($true, $false)",
        "      $ExpectedInheritance = if ($Directory) { $DirectoryInheritance } else { $NoInheritance }",
        "      foreach ($Sid in @($CurrentSid, $SystemSid, $AdministratorsSid)) {",
        "        $Rule = [Security.AccessControl.FileSystemAccessRule]::new($Sid, $FullControl, $ExpectedInheritance, $NoPropagation, [Security.AccessControl.AccessControlType]::Allow)",
        "        [void]$Security.AddAccessRule($Rule)",
        "      }",
        "      if ($Directory) { [IO.Directory]::SetAccessControl($Target, $Security) } else { [IO.File]::SetAccessControl($Target, $Security) }",
        "      $Sections = [Security.AccessControl.AccessControlSections]::Owner -bor [Security.AccessControl.AccessControlSections]::Access",
        "      $Observed = if ($Directory) { [IO.Directory]::GetAccessControl($Target, $Sections) } else { [IO.File]::GetAccessControl($Target, $Sections) }",
        "      if (-not $Observed.AreAccessRulesProtected -or $Observed.GetOwner([Security.Principal.SecurityIdentifier]).Value -ne $CurrentSid.Value) { throw 'hyper-v-base-image-acl-failed' }",
        "      $ObservedRules = @($Observed.GetAccessRules($true, $true, [Security.Principal.SecurityIdentifier]))",
        "      if ($ObservedRules.Count -ne $AllowedSids.Count) { throw 'hyper-v-base-image-acl-failed' }",
        "      foreach ($AllowedSid in $AllowedSids) {",
        "        $Matching = @($ObservedRules | Where-Object { $_.IdentityReference.Value -eq $AllowedSid })",
        "        if ($Matching.Count -ne 1 -or $Matching[0].AccessControlType -ne [Security.AccessControl.AccessControlType]::Allow -or $Matching[0].FileSystemRights -ne $FullControl -or $Matching[0].InheritanceFlags -ne $ExpectedInheritance -or $Matching[0].PropagationFlags -ne $NoPropagation -or $Matching[0].IsInherited) { throw 'hyper-v-base-image-acl-failed' }",
        "      }",
        "    }",
        "    Set-CccExactAcl $Path $true",
        "    $Pending = [Collections.Generic.Stack[string]]::new()",
        "    $Pending.Push($Path)",
        "    while ($Pending.Count -gt 0) {",
        "      $Parent = $Pending.Pop()",
        "      foreach ($Entry in @(Get-ChildItem -LiteralPath $Parent -Force -ErrorAction Stop)) {",
        "        if (($Entry.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) { throw 'hyper-v-base-image-acl-failed' }",
        "        Set-CccExactAcl $Entry.FullName $Entry.PSIsContainer",
        "        if ($Entry.PSIsContainer) { $Pending.Push($Entry.FullName) }",
        "      }",
        "    }",
        "  } catch {",
        "    if ([string]$_.Exception.Message -eq 'hyper-v-base-image-acl-failed') { throw }",
        "    throw 'hyper-v-base-image-acl-failed'",
        "  }",
        "}",
        "$ArchiveGuard = $null",
        "$SourceGuard = $null",
        "$NormalizedOutput = $null",
        "$PartialGuard = $null",
        "try {",
        "Assert-NoReparsePath $ImageRoot",
        "Assert-NoReparsePath $ProfileRoot",
        "Assert-NoReparsePath $ImagePath",
        "Assert-NoReparsePath $PartialPath",
        "Assert-NoReparsePath $WorkPath",
        "Assert-NoReparsePath $SourceArchivePath",
        "Import-Module Hyper-V -ErrorAction Stop",
        "Add-Type -AssemblyName System.Net.Http -ErrorAction Stop",
        "function Assert-BaseVhd([string]$Path) {",
        "  $Vhd = Get-VHD -Path $Path -ErrorAction Stop",
        "  if ([string]$Vhd.VhdFormat -ne 'VHDX' -or [string]$Vhd.VhdType -eq 'Differencing' -or $Vhd.ParentPath) { throw 'hyper-v-base-image-invalid-parent' }",
        "  return $Vhd",
        "}",
        "function Write-BaseObservation([object]$Vhd, [int]$Generation, [bool]$Reused, [string]$ExpectedHash = '') {",
        "  $Hash = (Get-FileHash -LiteralPath $ImagePath -Algorithm SHA256 -ErrorAction Stop).Hash.ToLowerInvariant()",
        "  if ($ExpectedHash -and $Hash -ne $ExpectedHash) { throw 'hyper-v-base-image-final-hash-mismatch' }",
        "  $Result = [ordered]@{ ok = $true; profile = $Profile; imagePath = $ImagePath; sha256 = $Hash; sizeBytes = [long](Get-Item -LiteralPath $ImagePath -ErrorAction Stop).Length; virtualSizeBytes = [long]$Vhd.Size; vhdType = [string]$Vhd.VhdType; generation = $Generation; reused = $Reused }",
        "  $Json = $Result | ConvertTo-Json -Compress -Depth 5",
        `  [Console]::Out.WriteLine('${HYPER_V_RESULT_MARKER}' + [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($Json)))`,
        "}",
        "function Save-BoundedDownload([string]$Uri, [string]$Destination, [long]$MaximumBytes, [scriptblock]$ValidateHopUri, [scriptblock]$ValidateFinalUri) {",
        "  $Handler = [System.Net.Http.HttpClientHandler]::new()",
        "  $Handler.AllowAutoRedirect = $false",
        "  $Client = [System.Net.Http.HttpClient]::new($Handler)",
        "  $Response = $null",
        "  $InputStream = $null",
        "  $OutputStream = $null",
        "  try {",
        "    $CurrentUri = [Uri]$Uri",
        "    for ($Redirects = 0; $Redirects -le 10; $Redirects++) {",
        "      if (-not (& $ValidateHopUri $CurrentUri)) { throw 'hyper-v-base-image-download-host-rejected' }",
        "      $Response = $Client.GetAsync($CurrentUri, [System.Net.Http.HttpCompletionOption]::ResponseHeadersRead).GetAwaiter().GetResult()",
        "      if ([int]$Response.StatusCode -ge 300 -and [int]$Response.StatusCode -lt 400) {",
        "        if ($Redirects -eq 10 -or $null -eq $Response.Headers.Location) { throw 'hyper-v-base-image-download-redirect-invalid' }",
        "        $CurrentUri = [Uri]::new($CurrentUri, $Response.Headers.Location)",
        "        $Response.Dispose()",
        "        $Response = $null",
        "        continue",
        "      }",
        "      break",
        "    }",
        "    if (-not $Response.IsSuccessStatusCode) { throw ('hyper-v-base-image-download-http-' + [int]$Response.StatusCode) }",
        "    $FinalUri = $CurrentUri",
        "    if (-not (& $ValidateFinalUri $FinalUri)) { throw 'hyper-v-base-image-download-host-rejected' }",
        "    $ContentLength = $Response.Content.Headers.ContentLength",
        "    if ($null -eq $ContentLength -or [long]$ContentLength -le 0 -or [long]$ContentLength -gt $MaximumBytes) { throw 'hyper-v-base-image-download-size-rejected' }",
        "    $InputStream = $Response.Content.ReadAsStreamAsync().GetAwaiter().GetResult()",
        "    $OutputStream = [IO.File]::Open($Destination, [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)",
        "    $Buffer = New-Object byte[] 1048576",
        "    $Written = [long]0",
        "    while (($Read = $InputStream.Read($Buffer, 0, $Buffer.Length)) -gt 0) {",
        "      $Written += $Read",
        "      if ($Written -gt $MaximumBytes) { throw 'hyper-v-base-image-download-size-rejected' }",
        "      $OutputStream.Write($Buffer, 0, $Read)",
        "    }",
        "    if ($Written -ne [long]$ContentLength) { throw 'hyper-v-base-image-download-length-mismatch' }",
        "  } finally {",
        "    if ($OutputStream) { $OutputStream.Dispose() }",
        "    if ($InputStream) { $InputStream.Dispose() }",
        "    if ($Response) { $Response.Dispose() }",
        "    $Client.Dispose()",
        "    $Handler.Dispose()",
        "  }",
        "}",
        "New-Item -ItemType Directory -Path $ProfileRoot -Force | Out-Null",
        "Protect-CccImageDirectory $ProfileRoot",
        "Assert-NoReparsePath $PartialPath",
        "Remove-Item -LiteralPath $PartialPath -Force -ErrorAction SilentlyContinue",
        "Assert-NoReparsePath $WorkPath",
        "if (Test-Path -LiteralPath $WorkPath) { throw 'hyper-v-base-image-work-path-not-clean' }",
        "if (Test-Path -LiteralPath $ImagePath) { throw 'hyper-v-base-image-unmanaged-existing' }",
        "  if ($Profile -eq 'windows-server') {",
        "    Set-CccAcquireStage 'hyper-v-base-image-download-failed'",
        "    $ValidateMicrosoftHop = { param([Uri]$CandidateUri) $HostName = $CandidateUri.DnsSafeHost.ToLowerInvariant(); return ($CandidateUri.Scheme -eq 'https' -and ($HostName -eq 'go.microsoft.com' -or $HostName -eq 'aka.ms' -or $HostName -eq 'download.microsoft.com' -or $HostName.EndsWith('.download.microsoft.com') -or $HostName -eq 'software-static.download.prss.microsoft.com')) }",
        "    $ValidateMicrosoftVhdx = { param([Uri]$FinalUri) $HostName = $FinalUri.DnsSafeHost.ToLowerInvariant(); return ($FinalUri.Scheme -eq 'https' -and $FinalUri.AbsolutePath.EndsWith('.vhdx', [StringComparison]::OrdinalIgnoreCase) -and ($HostName -eq 'download.microsoft.com' -or $HostName.EndsWith('.download.microsoft.com') -or $HostName -eq 'software-static.download.prss.microsoft.com')) }",
        "    Save-BoundedDownload $WindowsUrl $PartialPath $WindowsMaxBytes $ValidateMicrosoftHop $ValidateMicrosoftVhdx",
        "  } else {",
        ...hyperVUbuntuAzureImageAcquisitionLines(),
        "  }",
        "  Protect-CccImageDirectory $ProfileRoot",
        "  Set-CccAcquireStage 'hyper-v-base-image-partial-open-failed'",
        "  $PartialGuard = [IO.File]::Open($PartialPath, [IO.FileMode]::Open, [IO.FileAccess]::Read, ([IO.FileShare]::ReadWrite -bor [IO.FileShare]::Delete))",
        "  try {",
        "    Set-CccAcquireStage 'hyper-v-base-image-partial-hash-failed'",
        "    $PartialHashBefore = (Get-FileHash -LiteralPath $PartialPath -Algorithm SHA256 -ErrorAction Stop).Hash.ToLowerInvariant()",
        "    Set-CccAcquireStage 'hyper-v-base-image-partial-inspection-failed'",
        "    $Vhd = Assert-BaseVhd $PartialPath",
        "  } finally { $PartialGuard.Dispose(); $PartialGuard = $null }",
        "  $Generation = $ExpectedGeneration",
        "  Set-CccAcquireStage 'hyper-v-base-image-partial-open-failed'",
        "  $PartialGuard = [IO.File]::Open($PartialPath, [IO.FileMode]::Open, [IO.FileAccess]::Read, ([IO.FileShare]::ReadWrite -bor [IO.FileShare]::Delete))",
        "  try {",
        "    Set-CccAcquireStage 'hyper-v-base-image-partial-hash-failed'",
        "    $ValidatedPartialHash = (Get-FileHash -LiteralPath $PartialPath -Algorithm SHA256 -ErrorAction Stop).Hash.ToLowerInvariant()",
        "    if ($ValidatedPartialHash -ne $PartialHashBefore) { throw 'hyper-v-base-image-partial-mutated' }",
        "  } finally { $PartialGuard.Dispose(); $PartialGuard = $null }",
        "  Assert-NoReparsePath $PartialPath",
        "  Assert-NoReparsePath $ImagePath",
        "  Set-CccAcquireStage 'hyper-v-base-image-final-move-failed'",
        "  Move-Item -LiteralPath $PartialPath -Destination $ImagePath -ErrorAction Stop",
        "  Protect-CccImageDirectory $ProfileRoot",
        "  Set-CccAcquireStage 'hyper-v-base-image-final-inspection-failed'",
        "  $FinalHashBefore = (Get-FileHash -LiteralPath $ImagePath -Algorithm SHA256 -ErrorAction Stop).Hash.ToLowerInvariant()",
        "  if ($FinalHashBefore -ne $ValidatedPartialHash) { throw 'hyper-v-base-image-final-hash-mismatch' }",
        "  $Vhd = Assert-BaseVhd $ImagePath",
        "  Set-CccAcquireStage 'hyper-v-base-image-final-observation-failed'",
        "  Write-BaseObservation $Vhd $Generation $false $ValidatedPartialHash",
        "} catch {",
        "  $FailureMessage = [string]$_.Exception.Message",
        "  if ($FailureMessage -match '^hyper-v-[a-z0-9-]{3,128}$') { throw $FailureMessage }",
        "  [Console]::Out.WriteLine(('CCC_HYPER_V_STAGE:' + $script:CccAcquireStage))",
        "  throw $script:CccAcquireStage",
        "} finally {",
        "  if ($PartialGuard) { $PartialGuard.Dispose(); $PartialGuard = $null }",
        "  if ($NormalizedOutput) { $NormalizedOutput.Dispose(); $NormalizedOutput = $null }",
        "  if ($SourceGuard) { $SourceGuard.Dispose(); $SourceGuard = $null }",
        "  if ($ArchiveGuard) { $ArchiveGuard.Dispose(); $ArchiveGuard = $null }",
        "  Assert-NoReparsePath $PartialPath",
        "  Remove-Item -LiteralPath $PartialPath -Force -ErrorAction SilentlyContinue",
        "  Assert-NoReparsePath $WorkPath",
        "  if (Test-Path -LiteralPath $WorkPath) {",
        "    $UnsafeWorkEntries = @(Get-ChildItem -LiteralPath $WorkPath -Recurse -Force -ErrorAction Stop | Where-Object { ($_.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0 })",
        "    if ($UnsafeWorkEntries.Count -ne 0) { throw 'hyper-v-base-image-work-cleanup-failed' }",
        "    Remove-Item -LiteralPath $WorkPath -Recurse -Force -ErrorAction Stop",
        "  }",
        "}",
    ], undefined, true);
    return command(options.executable, script);
}
