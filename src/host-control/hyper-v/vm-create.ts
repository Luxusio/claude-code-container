import {
    type HyperVProviderCommand,
    type HyperVCreateOptions,
} from "./contracts.js";
import {
    psQuote,
    boundedInteger,
    assertIdentity,
    assertPlainPath,
    assertPathInside,
    ownershipMarker,
    jsonScript,
    command,
} from "./core.js";

export function hyperVCreateCommand(options: HyperVCreateOptions): HyperVProviderCommand {
    assertIdentity(options);
    const baseImagePath = assertPathInside(options.baseImageRoot, options.baseImagePath, "base-image-path");
    if (!/\.vhdx$/i.test(baseImagePath)) throw new Error("hyper-v-base-image-format-unsupported");
    const baseImageSha256 = String(options.baseImageSha256 || "").toLowerCase();
    if (!/^[a-f0-9]{64}$/.test(baseImageSha256)) throw new Error("hyper-v-base-image-sha256-invalid");
    if (options.baseImageGeneration !== 1 && options.baseImageGeneration !== 2) throw new Error("hyper-v-base-image-generation-invalid");
    const deviceRoot = assertPlainPath(options.deviceRoot, "device-root");
    const diskPath = assertPathInside(deviceRoot, String(options.diskPath || ""), "disk-path");
    if (!/\.vhdx$/i.test(diskPath)) throw new Error("hyper-v-disk-format-unsupported");
    const memoryMb = boundedInteger(options.memoryMb, 1024, 131072, "memory-mb");
    const cpus = boundedInteger(options.cpus, 1, 64, "cpus");
    const diskMaxBytes = boundedInteger(options.diskMaxBytes, 1024 * 1024 * 1024, Number.MAX_SAFE_INTEGER, "disk-max-bytes");
    const marker = ownershipMarker(options.ownerId, options.deviceId, options.incarnationId);
    const secureBootEnabled = options.secureBootEnabled !== false;
    if (secureBootEnabled && options.baseImageGeneration !== 2) throw new Error("hyper-v-secure-boot-generation-invalid");
    const secureBootTemplate = options.secureBootTemplate || "MicrosoftWindows";
    const switchName = options.switchName ? String(options.switchName) : "";
    if (switchName.length > 128 || /[\u0000-\u001f]/.test(switchName)) throw new Error("hyper-v-switch-name-invalid");
    const macAddress = options.macAddress ? String(options.macAddress).toUpperCase() : "";
    if (macAddress && !/^02(?::[0-9A-F]{2}){5}$/.test(macAddress)) throw new Error("hyper-v-mac-address-invalid");
    const bootstrapMacAddress = macAddress ? `06${macAddress.slice(2)}` : "";
    if (options.bootstrapDhcp === true && !bootstrapMacAddress) throw new Error("hyper-v-bootstrap-mac-address-missing");
    const checkpointType = options.checkpointType || "ProductionOnly";
    if (checkpointType !== "Production" && checkpointType !== "ProductionOnly") throw new Error("hyper-v-checkpoint-type-invalid");
    const lines = [
        `$VmName = ${psQuote(options.vmName)}`,
        `$Marker = ${psQuote(marker)}`,
        `$BaseImage = ${psQuote(baseImagePath)}`,
        `$ExpectedBaseImageHash = ${psQuote(baseImageSha256)}`,
        `$ExpectedVmGeneration = ${options.baseImageGeneration}`,
        `$DeviceRoot = ${psQuote(deviceRoot)}`,
        `$DiskPath = ${psQuote(diskPath)}`,
        "$DiskDirectory = Split-Path -Parent $DiskPath",
        `$DiskMaxBytes = [long]${diskMaxBytes}`,
        `$SwitchName = ${psQuote(switchName)}`,
        `$MacAddress = ${psQuote(macAddress)}`,
        `$BootstrapMacAddress = ${psQuote(bootstrapMacAddress)}`,
        `$Networking = ${options.networking === false ? "$false" : "$true"}`,
        `$BootstrapDhcp = ${options.bootstrapDhcp === true ? "$true" : "$false"}`,
        "function Set-CccVmCreateStage([string]$Stage) {",
        "  $env:CCC_HYPER_V_STAGE = $Stage",
        "  [Console]::Out.WriteLine(('CCC_HYPER_V_STAGE:' + $Stage))",
        "}",
        "function Set-CccPrivateDirectoryAcl([string]$Path) {",
        "  try {",
        "    $CurrentSid = [Security.Principal.WindowsIdentity]::GetCurrent().User",
        "    $AllowedSids = @($CurrentSid, [Security.Principal.SecurityIdentifier]::new('S-1-5-18'), [Security.Principal.SecurityIdentifier]::new('S-1-5-32-544'))",
        "    $Inheritance = [Security.AccessControl.InheritanceFlags]::ContainerInherit -bor [Security.AccessControl.InheritanceFlags]::ObjectInherit",
        "    $Acl = Get-Acl -LiteralPath $Path -ErrorAction Stop",
        "    $Acl.SetAccessRuleProtection($true, $false)",
        "    foreach ($Rule in @($Acl.Access)) { [void]$Acl.RemoveAccessRuleAll($Rule) }",
        "    $Acl.SetOwner($CurrentSid)",
        "    foreach ($Sid in $AllowedSids) {",
        "      $Rule = [Security.AccessControl.FileSystemAccessRule]::new($Sid, [Security.AccessControl.FileSystemRights]::FullControl, $Inheritance, [Security.AccessControl.PropagationFlags]::None, [Security.AccessControl.AccessControlType]::Allow)",
        "      [void]$Acl.AddAccessRule($Rule)",
        "    }",
        "    Set-Acl -LiteralPath $Path -AclObject $Acl -ErrorAction Stop",
        "    $ObservedAcl = Get-Acl -LiteralPath $Path -ErrorAction Stop",
        "    if (-not $ObservedAcl.AreAccessRulesProtected) { throw 'hyper-v-device-root-acl-failed' }",
        "    if ($ObservedAcl.GetOwner([Security.Principal.SecurityIdentifier]).Value -ne $CurrentSid.Value) { throw 'hyper-v-device-root-acl-failed' }",
        "    $ObservedRules = @($ObservedAcl.Access)",
        "    if ($ObservedRules.Count -ne $AllowedSids.Count) { throw 'hyper-v-device-root-acl-failed' }",
        "    foreach ($AllowedSid in $AllowedSids) {",
        "      $MatchingRules = @($ObservedRules | Where-Object { $_.IdentityReference.Translate([Security.Principal.SecurityIdentifier]).Value -eq $AllowedSid.Value })",
        "      if ($MatchingRules.Count -ne 1) { throw 'hyper-v-device-root-acl-failed' }",
        "    }",
        "    foreach ($ObservedRule in $ObservedRules) {",
        "      $ObservedSid = $ObservedRule.IdentityReference.Translate([Security.Principal.SecurityIdentifier]).Value",
        "      if ($AllowedSids.Value -notcontains $ObservedSid -or $ObservedRule.IsInherited -or $ObservedRule.AccessControlType -ne [Security.AccessControl.AccessControlType]::Allow -or [int]$ObservedRule.FileSystemRights -ne [int][Security.AccessControl.FileSystemRights]::FullControl -or $ObservedRule.InheritanceFlags -ne $Inheritance -or $ObservedRule.PropagationFlags -ne [Security.AccessControl.PropagationFlags]::None) { throw 'hyper-v-device-root-acl-failed' }",
        "    }",
        "  } catch { throw 'hyper-v-device-root-acl-failed' }",
        "}",
        "Set-CccVmCreateStage 'hyper-v-host-capacity-inspection-failed'",
        "$ComputerInfo = Get-CimInstance Win32_ComputerSystem -ErrorAction Stop",
        "$TotalMemoryMb = [Math]::Floor([double]$ComputerInfo.TotalPhysicalMemory / 1MB)",
        "$MemoryReserveMb = [Math]::Max(2048, [Math]::Floor($TotalMemoryMb * 0.10))",
        `if (${memoryMb} -gt ($TotalMemoryMb - $MemoryReserveMb)) { throw 'hyper-v-host-memory-capacity-exceeded' }`,
        `if (${cpus} -gt ([int]$ComputerInfo.NumberOfLogicalProcessors * 2)) { throw 'hyper-v-host-cpu-capacity-exceeded' }`,
        "Set-CccVmCreateStage 'hyper-v-host-storage-inspection-failed'",
        "$DiskRoot = [IO.Path]::GetPathRoot($DiskPath)",
        "$DiskDriveName = $DiskRoot.TrimEnd('\\').TrimEnd(':')",
        "$DiskDrive = Get-PSDrive -Name $DiskDriveName -PSProvider FileSystem -ErrorAction Stop",
        "$DiskReserveBytes = 10GB",
        "if ([long]$DiskDrive.Free -lt ($DiskMaxBytes + $DiskReserveBytes)) { throw 'hyper-v-host-disk-capacity-exceeded' }",
        "Set-CccVmCreateStage 'hyper-v-vm-path-inspection-failed'",
        "Assert-NoReparsePath $BaseImage",
        "Assert-NoReparsePath $DeviceRoot",
        "Assert-NoReparsePath $DiskPath",
        "if (-not (Test-Path -LiteralPath $BaseImage -PathType Leaf)) { throw 'hyper-v-base-image-not-found' }",
        "Set-CccVmCreateStage 'hyper-v-vm-identity-inspection-failed'",
        "if (Get-VM -Name $VmName -ErrorAction SilentlyContinue) { throw 'hyper-v-vm-already-exists' }",
        "$DeviceRootExisted = Test-Path -LiteralPath $DeviceRoot",
        "$CreatedVm = $null",
        "$BaseImageStream = $null",
        "$DiskCopySource = $null",
        "$DiskCopyOutput = $null",
        "try {",
        "  New-Item -ItemType Directory -Path $DeviceRoot -Force | Out-Null",
        "  Set-CccPrivateDirectoryAcl $DeviceRoot",
        "  Assert-NoReparsePath $DiskDirectory",
        "  New-Item -ItemType Directory -Path $DiskDirectory -Force | Out-Null",
        "  Set-CccPrivateDirectoryAcl $DiskDirectory",
        "  $ResolvedSwitch = $null",
        "  $BootstrapSwitch = $null",
        "  if ($Networking) {",
        "    Set-CccVmCreateStage 'hyper-v-network-switch-inspection-failed'",
        "    if ($SwitchName) {",
        "      $SwitchMatches = @(Get-VMSwitch -Name $SwitchName -ErrorAction SilentlyContinue)",
        "      if ($SwitchMatches.Count -ne 1) { throw 'hyper-v-network-switch-not-found' }",
        "      $ResolvedSwitch = $SwitchMatches[0]",
        "    } else {",
        "      $ResolvedSwitch = Get-VMSwitch -Name 'Default Switch' -ErrorAction SilentlyContinue | Select-Object -First 1",
        "      if (-not $ResolvedSwitch) { $ResolvedSwitch = Get-VMSwitch -ErrorAction Stop | Where-Object { $_.SwitchType -eq 'External' } | Sort-Object Name | Select-Object -First 1 }",
        "      if (-not $ResolvedSwitch) { $ResolvedSwitch = Get-VMSwitch -ErrorAction Stop | Where-Object { $_.SwitchType -eq 'Internal' } | Sort-Object Name | Select-Object -First 1 }",
        "      if (-not $ResolvedSwitch) { throw 'hyper-v-network-switch-unavailable' }",
        "    }",
        "    if ($BootstrapDhcp) {",
        "      if (-not $SwitchName) { throw 'hyper-v-bootstrap-network-switch-required' }",
        "      $BootstrapSwitches = @(Get-VMSwitch -Name 'Default Switch' -ErrorAction SilentlyContinue)",
        "      if ($BootstrapSwitches.Count -ne 1) { throw 'hyper-v-bootstrap-dhcp-switch-unavailable' }",
        "      $BootstrapSwitch = $BootstrapSwitches[0]",
        "      if ([string]$BootstrapSwitch.Id -eq [string]$ResolvedSwitch.Id) { throw 'hyper-v-bootstrap-network-switch-conflict' }",
        "      $BootstrapMacHex = $BootstrapMacAddress.Replace(':', '')",
        "      $BootstrapMacConflicts = @(Get-VMNetworkAdapter -All -ErrorAction Stop | Where-Object { ([string]$_.MacAddress).ToUpperInvariant() -eq $BootstrapMacHex })",
        "      if ($BootstrapMacConflicts.Count -gt 0) { throw 'hyper-v-bootstrap-mac-address-conflict' }",
        "    }",
        "  }",
        "  Assert-NoReparsePath $BaseImage",
        "  Assert-NoReparsePath $DiskPath",
        "  Set-CccVmCreateStage 'hyper-v-base-image-hash-failed'",
        "  $BaseImageStream = [IO.File]::Open($BaseImage, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::Read)",
        "  $Hasher = [Security.Cryptography.SHA256]::Create()",
        "  try { $BaseImageHash = ([BitConverter]::ToString($Hasher.ComputeHash($BaseImageStream))).Replace('-', '').ToLowerInvariant() } finally { $Hasher.Dispose() }",
        "  if ($BaseImageHash -ne $ExpectedBaseImageHash) { throw 'hyper-v-base-image-hash-mismatch' }",
        "  $BaseImageStream.Dispose()",
        "  $BaseImageStream = $null",
        "  Set-CccVmCreateStage 'hyper-v-base-image-inspection-failed'",
        "  $BaseVhd = Get-VHD -Path $BaseImage -ErrorAction Stop",
        "  if ([string]$BaseVhd.VhdType -eq 'Differencing' -or $BaseVhd.ParentPath) { throw 'hyper-v-base-image-parent-invalid' }",
        "  Set-CccVmCreateStage 'hyper-v-vm-disk-create-failed'",
        "  Assert-NoReparsePath $BaseImage",
        "  Assert-NoReparsePath $DiskPath",
        "  $DiskCopyFailure = $null",
        "  try {",
        "    $DiskCopySource = [IO.File]::Open($BaseImage, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::Read)",
        "    $DiskCopyOutput = [IO.File]::Open($DiskPath, [IO.FileMode]::CreateNew, [IO.FileAccess]::ReadWrite, [IO.FileShare]::None)",
        "    $Hasher = [Security.Cryptography.SHA256]::Create()",
        "    try { $CopySourceHash = ([BitConverter]::ToString($Hasher.ComputeHash($DiskCopySource))).Replace('-', '').ToLowerInvariant() } finally { $Hasher.Dispose() }",
        "    if ($CopySourceHash -ne $ExpectedBaseImageHash) { throw 'hyper-v-base-image-hash-mismatch' }",
        "    $DiskCopySource.Position = 0",
        "    $DiskCopySource.CopyTo($DiskCopyOutput, 8MB)",
        "    $DiskCopyOutput.Flush($true)",
        "    $CopySourceLength = [long]$DiskCopySource.Length",
        "    $DiskCopyOutput.Position = 0",
        "    $Hasher = [Security.Cryptography.SHA256]::Create()",
        "    try { $ClonedDiskHash = ([BitConverter]::ToString($Hasher.ComputeHash($DiskCopyOutput))).Replace('-', '').ToLowerInvariant() } finally { $Hasher.Dispose() }",
        "    if ($ClonedDiskHash -ne $ExpectedBaseImageHash) { throw 'hyper-v-created-disk-hash-mismatch' }",
        "    $ClonedDiskLength = [long]$DiskCopyOutput.Length",
        "  } catch {",
        "    $DiskCopyFailure = $_",
        "  } finally {",
        "    try { if ($DiskCopyOutput) { $DiskCopyOutput.Dispose() } } catch { if (-not $DiskCopyFailure) { $DiskCopyFailure = $_ } }",
        "    $DiskCopyOutput = $null",
        "    try { if ($DiskCopySource) { $DiskCopySource.Dispose() } } catch { if (-not $DiskCopyFailure) { $DiskCopyFailure = $_ } }",
        "    $DiskCopySource = $null",
        "  }",
        "  if ($DiskCopyFailure) { throw $DiskCopyFailure }",
        "  if ($ClonedDiskLength -ne $CopySourceLength) { throw 'hyper-v-created-disk-length-mismatch' }",
        "  $CreatedDisk = Get-VHD -Path $DiskPath -ErrorAction Stop",
        "  if ([string]$CreatedDisk.VhdFormat -ne 'VHDX' -or [string]$CreatedDisk.VhdType -eq 'Differencing' -or $CreatedDisk.ParentPath -or [long]$CreatedDisk.Size -ne [long]$BaseVhd.Size) { throw 'hyper-v-created-disk-format-mismatch' }",
        "  $VmGeneration = $ExpectedVmGeneration",
        "  Set-CccVmCreateStage 'hyper-v-base-image-hash-failed'",
        "  $BaseImageStream = [IO.File]::Open($BaseImage, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::Read)",
        "  $BaseImageStream.Position = 0",
        "  $Hasher = [Security.Cryptography.SHA256]::Create()",
        "  try { $BaseImageHashAfterCreate = ([BitConverter]::ToString($Hasher.ComputeHash($BaseImageStream))).Replace('-', '').ToLowerInvariant() } finally { $Hasher.Dispose() }",
        "  if ($BaseImageHashAfterCreate -ne $ExpectedBaseImageHash) { throw 'hyper-v-base-image-hash-mismatch' }",
        "  $BaseImageStream.Dispose()",
        "  $BaseImageStream = $null",
        `  $VmArgs = @{ Name = $VmName; Generation = $VmGeneration; MemoryStartupBytes = ${memoryMb}MB; VHDPath = $DiskPath; BootDevice = 'VHD' }`,
        "  if ($BootstrapSwitch) { $VmArgs.SwitchName = $BootstrapSwitch.Name } elseif ($ResolvedSwitch) { $VmArgs.SwitchName = $ResolvedSwitch.Name }",
        "  Set-CccVmCreateStage 'hyper-v-vm-create-failed'",
        "  $CreatedVm = New-VM @VmArgs -ErrorAction Stop",
        "  Set-CccVmCreateStage 'hyper-v-vm-configure-failed'",
        "  $ManagedAdapter = $null",
        "  if ($BootstrapSwitch) {",
        "    $BootstrapAdapters = @(Get-VMNetworkAdapter -VM $CreatedVm -ErrorAction Stop)",
        "    if ($BootstrapAdapters.Count -ne 1) { throw 'hyper-v-bootstrap-network-adapter-unavailable' }",
        "    Rename-VMNetworkAdapter -VMNetworkAdapter $BootstrapAdapters[0] -NewName 'CCC Bootstrap DHCP' -ErrorAction Stop",
        "    Set-VMNetworkAdapter -VMNetworkAdapter $BootstrapAdapters[0] -StaticMacAddress ($BootstrapMacAddress.Replace(':', '')) -ErrorAction Stop",
        "    Add-VMNetworkAdapter -VM $CreatedVm -SwitchName $ResolvedSwitch.Name -Name 'CCC Device Network' -ErrorAction Stop",
        "    $ManagedAdapters = @(Get-VMNetworkAdapter -VM $CreatedVm -ErrorAction Stop | Where-Object { $_.Name -eq 'CCC Device Network' })",
        "    if ($ManagedAdapters.Count -ne 1) { throw 'hyper-v-managed-network-adapter-unavailable' }",
        "    $ManagedAdapter = $ManagedAdapters[0]",
        "  } else {",
        "    $ManagedAdapters = @(Get-VMNetworkAdapter -VM $CreatedVm -ErrorAction Stop)",
        "    if ($ManagedAdapters.Count -eq 1) { $ManagedAdapter = $ManagedAdapters[0] }",
        "  }",
        "  if ($MacAddress) {",
        "    if (-not $ManagedAdapter) { throw 'hyper-v-managed-network-adapter-unavailable' }",
        "    Set-VMNetworkAdapter -VMNetworkAdapter $ManagedAdapter -StaticMacAddress ($MacAddress.Replace(':', '')) -ErrorAction Stop",
        "  }",
        "  if ($BootstrapSwitch) {",
        "    $AssignedBootstrapMatches = @(Get-VMNetworkAdapter -All -ErrorAction Stop | Where-Object { ([string]$_.MacAddress).ToUpperInvariant() -eq $BootstrapMacAddress.Replace(':', '') })",
        "    if ($AssignedBootstrapMatches.Count -ne 1 -or [string]$AssignedBootstrapMatches[0].VMId -ne [string]$CreatedVm.Id -or [string]$AssignedBootstrapMatches[0].Name -cne 'CCC Bootstrap DHCP') { throw 'hyper-v-bootstrap-mac-address-conflict' }",
        "  }",
        `  Set-VMProcessor -VM $CreatedVm -Count ${cpus} -ErrorAction Stop`,
        "  Set-VMMemory -VM $CreatedVm -DynamicMemoryEnabled $false -ErrorAction Stop",
        `  Set-VM -VM $CreatedVm -AutomaticCheckpointsEnabled $false -CheckpointType ${checkpointType} -Notes $Marker -ErrorAction Stop`,
        "  $CreatedOsDisks = @(Get-VMHardDiskDrive -VM $CreatedVm -ErrorAction Stop | Where-Object { [string]$_.Path -eq $DiskPath })",
        "  if ($CreatedOsDisks.Count -ne 1) { throw 'hyper-v-created-disk-attachment-mismatch' }",
        "  if ($VmGeneration -eq 2) {",
        ...(secureBootEnabled
            ? [`    Set-VMFirmware -VM $CreatedVm -EnableSecureBoot On -SecureBootTemplate ${psQuote(secureBootTemplate)} -FirstBootDevice $CreatedOsDisks[0] -ErrorAction Stop`]
            : ["    Set-VMFirmware -VM $CreatedVm -EnableSecureBoot Off -FirstBootDevice $CreatedOsDisks[0] -ErrorAction Stop"]),
        "    $CreatedFirmware = Get-VMFirmware -VM $CreatedVm -ErrorAction Stop",
        "    $CreatedFirstBootDevice = @($CreatedFirmware.BootOrder)[0].Device",
        "    if (-not $CreatedFirstBootDevice -or [string]$CreatedFirstBootDevice.Path -ne $DiskPath) { throw 'hyper-v-created-disk-boot-order-mismatch' }",
        "  } else {",
        "    Set-VMBios -VM $CreatedVm -StartupOrder @('IDE','CD','LegacyNetworkAdapter','Floppy') -ErrorAction Stop",
        "  }",
        "  $Result = [ordered]@{ ok = $true; vmId = [string]$CreatedVm.Id; vmName = $CreatedVm.Name; state = [string]$CreatedVm.State; generation = $VmGeneration; diskPath = $DiskPath; switchName = if ($ResolvedSwitch) { $ResolvedSwitch.Name } else { $null } }",
        "  $Result | ConvertTo-Json -Compress -Depth 5",
        "} catch {",
        "  $PrimaryError = $_",
        "  try { if ($BaseImageStream) { $BaseImageStream.Dispose() } } catch { }",
        "  try { if ($DiskCopyOutput) { $DiskCopyOutput.Dispose() } } catch { }",
        "  try { if ($DiskCopySource) { $DiskCopySource.Dispose() } } catch { }",
        "  try { if ($CreatedVm) { Remove-VM -VM $CreatedVm -Force -ErrorAction Stop } } catch { }",
        "  try {",
        "    Assert-NoReparsePath $DiskPath",
        "    if (Test-Path -LiteralPath $DiskPath) { Remove-Item -LiteralPath $DiskPath -Force -ErrorAction SilentlyContinue }",
        "  } catch { }",
        "  try {",
        "    Assert-NoReparsePath $DeviceRoot",
        "    if (-not $DeviceRootExisted -and (Test-Path -LiteralPath $DeviceRoot)) { Remove-Item -LiteralPath $DeviceRoot -Recurse -Force -ErrorAction SilentlyContinue }",
        "  } catch { }",
        "  throw $PrimaryError",
        "}",
    ];
    return command(
        options.executable,
        jsonScript(lines, "hyper-v-vm-preflight-failed"),
    );
}
